"""Writes the adaptive launcher icon foreground (Orchard Drive at Sunset) as a VectorDrawable.

The 512-unit scene from store/icon.svg is placed in the middle 72dp of the 108dp adaptive
canvas (the part launcher masks show), with the sky, ground and road extended to the edges so
masks and parallax never reveal a gap.
"""
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "app/src/main/res/drawable/ic_app_icon_foreground.xml"
S = 72 / 512  # scene units -> dp
O = 18        # inset of the scene inside the 108dp canvas
SUNSET, NIGHT, ASPHALT, CANOPY, LEAF, BARK = "#FFFF5A45", "#FF0A0B0F", "#FF2D303C", "#FF0E1712", "#FF2F4A3A", "#FF08090C"


def circle(cx, cy, r):
    return f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z"


def rect(x, y, w, h):
    return f"M{x},{y}h{w}v{h}h{-w}z"


def path(d, fill=None, stroke=None, width=None, extra=""):
    attrs = f'android:pathData="{d}"'
    if fill:
        attrs += f' android:fillColor="{fill}"'
    if stroke:
        attrs += f' android:strokeColor="{stroke}" android:strokeWidth="{width}" android:strokeLineCap="round"'
    return f"<path {attrs}{extra} />"


def tree():
    """The orange tree symbol, in its own 100x126 units."""
    out = [path(rect(45.5, 78, 9, 48), BARK),
           path(circle(50, 32, 30) + circle(22, 58, 22) + circle(78, 58, 22) + circle(50, 64, 24), CANOPY),
           path("M50,100L35,85M50,100L65,85M50,104V80", stroke=BARK, width=6)]
    for cx, cy, rot in ((52, 24, -62), (18, 50, 24), (80, 50, -24)):
        out.append(f'<group android:rotation="{rot}" android:pivotX="{cx}" android:pivotY="{cy}">'
                   + path(f"M{cx - 7},{cy}a7,4 0 1,0 14,0a7,4 0 1,0 -14,0z", LEAF) + "</group>")
    out.append(path(circle(58, 40, 9.5) + circle(30, 62, 9.5) + circle(68, 66, 9.5), SUNSET))
    return "".join(out)


def placed_tree(x, y, scale):
    return f'<group android:translateX="{x}" android:translateY="{y}" android:scaleX="{scale}" android:scaleY="{scale}">{tree()}</group>'


# Everything below is in scene units; the outer group maps it to dp. The canvas edges are at
# -O/S and (108-O)/S in scene units.
lo, hi = -O / S, (108 - O) / S
horizon = 290
road_left = lambda y: 251 - (251 - 67) * (y - horizon) / (512 - horizon)
road_right = lambda y: 261 + (441 - 261) * (y - horizon) / (512 - horizon)
dashes = [(255, 292, 2, 2), (254.5, 297, 3, 2.5), (254, 304, 4, 4), (253.5, 314, 5, 7), (253, 330, 6, 10),
          (252, 351, 8, 14), (251, 384, 10, 21), (249, 427, 14, 33), (247.5, 485, 17, 27), (245.5, 545, 21, 40)]

scene = [
    f'<path android:pathData="{rect(lo, lo, hi - lo, horizon - lo)}"><aapt:attr name="android:fillColor">'
    f'<gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="{horizon}">'
    '<item android:offset="0" android:color="#FF141929" /><item android:offset="1" android:color="#FF1D2338" />'
    "</gradient></aapt:attr></path>",
    path(circle(257, 268, 124), SUNSET),
    placed_tree(-2, 140, 1.2), placed_tree(110, 206, 0.72),
    '<group android:translateX="512" android:scaleX="-1">' + placed_tree(-2, 140, 1.2) + placed_tree(144, 206, 0.72) + "</group>",
    path(rect(lo, horizon, hi - lo, hi - horizon), NIGHT),
    path(f"M251,{horizon}L261,{horizon}L{road_right(hi):.1f},{hi:.1f}L{road_left(hi):.1f},{hi:.1f}z", ASPHALT),
    path("".join(rect(*d) for d in dashes), SUNSET),
]

xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_icon_vector.py from the Orchard Drive at Sunset icon; edit that instead. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{O}" android:translateY="{O}" android:scaleX="{S}" android:scaleY="{S}">
        {"".join(scene)}
    </group>
</vector>
"""
with open(OUT, "w") as f:
    f.write(xml)
print("wrote", OUT)
